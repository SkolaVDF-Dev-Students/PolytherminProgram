    def __init__(self):
        self.lcd = Screen()
        self.lcd.clear()
        self.plot = self.lcd.create_plotter()

    def clear(self):
        self.lcd.clear()

    def show(self):
        self.lcd.redraw()

    def draw_text(self, text, x, y):
        for char in text.upper():
            if char in self.FONT:
                for row, byte in enumerate(self.FONT[char]):
                    for col in range(5):
                        if byte & (1 << (4 - col)):
                            self.plot(x + col, y + row)
                x += 6
        return x

    def draw_line(self, x1, y1, x2, y2):
        dx = abs(x2 - x1)
        dy = abs(y2 - y1)
        sx = 1 if x1 < x2 else -1
        sy = 1 if y1 < y2 else -1
        err = dx - dy

        while True:
            self.plot(x1, y1)
            if x1 == x2 and y1 == y2:
                break
            e2 = 2 * err
            if e2 > -dy:
                err -= dy
                x1 += sx
            if e2 < dx:
                err += dx
                y1 += sy

    def draw_rect(self, x1, y1, x2, y2):
        for x in range(x1, x2 + 1):
            self.plot(x, y1)
            self.plot(x, y2)
        for y in range(y1, y2 + 1):
            self.plot(x1, y)
            self.plot(x2, y)

    # vykreslí celé menu, selected_index = 0..3
    def draw_menu(self, selected_index):
        self.clear()

        items = ["BACK", "MENU1", "MENU2", "HEATING"]
        start_x = 5
        start_y = 5
        line_h = 12          # výška řádku
        box_margin_x = 2
        box_margin_y = 1

        for i, text in enumerate(items):
            y = start_y + i * line_h
            # text
            self.draw_text(text, start_x, y)
            # spočítáme šířku textu pro rámeček (6 px na znak, 5 aktivních + 1 mezera)
            text_width = len(text) * 6
            if i == selected_index:
                # rámeček kolem daného řádku
                x1 = start_x - box_margin_x
                y1 = y - box_margin_y
                x2 = start_x + text_width + box_margin_x
                y2 = y + 9 + box_margin_y  # 7 px font + rezerva
                self.draw_rect(x1, y1, x2, y2)

        self.show()


